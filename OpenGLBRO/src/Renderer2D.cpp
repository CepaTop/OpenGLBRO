static const uint8_t* buscarGlifo(char c)
{
    c = static_cast<char>(std::toupper(static_cast<unsigned char>(c)));
    const char* p = std::strchr(CARACTERES, c);
    if (c == '\0' || p == nullptr) return nullptr; // Espacio o carácter desconocido
    return GLIFOS[p - CARACTERES];
}

